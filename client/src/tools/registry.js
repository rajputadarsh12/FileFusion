export const getToolById = (id) => TOOLS.find((t) => t.id === id);
export const getToolsByCategory = (categoryId) => {
  if (!categoryId || categoryId === 'all') return TOOLS;
  return TOOLS.filter((t) => t.category === categoryId);
};
export const getPopularTools = () => TOOLS.filter((t) => t.popular);
export const getQuickActionTools = () => TOOLS.filter((t) => t.quickAction);
export const getRelatedTools = (toolId, limit = 4) => {
  const current = getToolById(toolId);
  if (!current) return [];
  const sameCategory = TOOLS.filter((t) => t.category === current.category && t.id !== toolId);
  if (sameCategory.length >= limit) return sameCategory.slice(0, limit);
  const others = TOOLS.filter((t) => t.category !== current.category && t.id !== toolId);
  return [...sameCategory, ...others].slice(0, limit);
};
